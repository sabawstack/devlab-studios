/**
 * Writes scripts/cms/updates/2026-11-12-privacy-page.sql from the static
 * privacy page (src/data/pages/privacy.js), so the D1 copy and the static
 * fallback carry the same text (audit SEC-03).
 *
 *   node scripts/cms/generate-privacy-update.mjs
 *
 * The SQL only UPDATEs existing privacy sections (matched by page slug and
 * block type); on a database without a privacy page row it changes nothing
 * and the static page is what visitors see anyway.
 */
import { writeFileSync } from 'node:fs'
import { privacyPage } from '../../src/data/pages/privacy.js'

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`
const lines = [
  '-- Privacy page text (audit SEC-03), generated by scripts/cms/generate-privacy-update.mjs.',
  '-- Idempotent: sets the privacy page sections to the static text. No-op when no privacy row exists.',
  '--   npx wrangler d1 execute devlab-studios-cms-preview --remote --env preview --file scripts/cms/updates/2026-11-12-privacy-page.sql',
  '--   npx wrangler d1 execute devlab-studios-cms --remote --file scripts/cms/updates/2026-11-12-privacy-page.sql',
  '',
]
for (const block of privacyPage.blocks) {
  lines.push(
    `UPDATE page_sections SET content_json = ${quote(JSON.stringify(block.props))}, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now')`,
    `WHERE section_type = ${quote(block.type)} AND page_id = (SELECT id FROM pages WHERE slug = 'privacy');`,
    '',
  )
}
writeFileSync('scripts/cms/updates/2026-11-12-privacy-page.sql', lines.join('\n'))
console.log('Wrote scripts/cms/updates/2026-11-12-privacy-page.sql')
